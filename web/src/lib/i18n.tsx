export const DICTS: Record<UiLang, Dict> = { pt, en };

const I18nContext = createContext<{ t: Dict; lang: UiLang }>({ t: pt, lang: 'pt' });

export function I18nProvider({ lang, children }: { lang: UiLang; children: ReactNode }) {
  return <I18nContext.Provider value={{ t: DICTS[lang], lang }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

export const reason = (t: Dict, code: string | null | undefined) => t.reasons[code ?? 'unknown'] ?? t.reasons.unknown;
